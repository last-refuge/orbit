#!/usr/bin/env python3
"""Write docs/dependency-inventory.md from `cargo metadata` for the Linux target.

Usage: scripts/license-inventory.py [--check]

--check exits non-zero when the committed inventory is out of date.
"""

import collections
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "dependency-inventory.md"
TARGET = "x86_64-unknown-linux-gnu"

# Third-party files vendored outside Cargo: (what, version, license, source, where).
VENDORED = [
    (
        "Inter (Regular, Medium, SemiBold, Bold)",
        "4.1",
        "OFL-1.1",
        "https://github.com/rsms/inter/releases/download/v4.1/Inter-4.1.zip "
        "(sha256 9883fdd4a49d4fb66bd8177ba6625ef9a64aa45899767dde3d36aa425756b11e); "
        "faces copied unchanged out of Inter.ttc",
        "crates/orbit-ui/assets/fonts/inter/",
    ),
    (
        "Hyprland protocol XML",
        "see each file",
        "BSD-3-Clause",
        "https://github.com/hyprwm/hyprland-protocols",
        "crates/orbit-capture/protocols/",
    ),
]


def source_label(source):
    if source is None:
        return "workspace"
    if source.startswith("registry+"):
        return "crates.io"
    url, _, rev = source.removeprefix("git+").partition("#")
    return f"git {url.split('?')[0]} @ {rev[:12]}"


def render():
    metadata = json.loads(
        subprocess.check_output(
            ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", TARGET],
            cwd=ROOT,
        )
    )
    resolved = {node["id"] for node in metadata["resolve"]["nodes"]}
    packages = sorted(
        (p for p in metadata["packages"] if p["id"] in resolved and p["source"] is not None),
        key=lambda p: (p["name"], p["version"]),
    )
    by_license = collections.Counter(p["license"] or "UNSPECIFIED" for p in packages)

    lines = [
        "# Dependency and license inventory",
        "",
        f"Generated by `scripts/license-inventory.py` for `{TARGET}`. Do not edit by hand.",
        "The allowed-license policy lives in `deny.toml`; CI runs both.",
        "",
        f"{len(packages)} third-party crates.",
        "",
        "## By license expression",
        "",
        "| License | Crates |",
        "| --- | --- |",
    ]
    lines += [f"| {lic} | {n} |" for lic, n in sorted(by_license.items(), key=lambda kv: (-kv[1], kv[0]))]
    lines += ["", "## Crates", "", "| Crate | Version | License | Source |", "| --- | --- | --- | --- |"]
    lines += [
        f"| {p['name']} | {p['version']} | {p['license'] or 'UNSPECIFIED'} | {source_label(p['source'])} |"
        for p in packages
    ]
    lines += [
        "",
        "## Vendored files",
        "",
        "| What | Version | License | Source | In |",
        "| --- | --- | --- | --- | --- |",
    ]
    lines += [f"| {w} | {v} | {lic} | {src} | `{at}` |" for w, v, lic, src, at in VENDORED]
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is out of date; run scripts/license-inventory.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
