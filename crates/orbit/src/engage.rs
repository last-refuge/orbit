//! Engaging Orbit from the keyboard (ORB-010): the shortcut bind.
//!
//! Wayland clients cannot grab global keys, so the bind belongs to Hyprland.
//! Orbit applies it live over IPC (`hl.bind` through `eval`, undone with
//! `hl.unbind` when the shortcut changes or the daemon quits) and owns a
//! generated Lua snippet, `$XDG_CONFIG_HOME/hypr/orbit.lua`, that makes it
//! permanent once `hyprland.lua` requires it. Orbit never edits
//! `hyprland.lua` itself; the settings window appends the one `require`
//! line only after the person confirms exactly what will be written.

use std::{
    fs,
    io::Write,
    path::{Path, PathBuf},
};

use orbit_core::settings::Shortcut;
use orbit_hyprland::Instance;

/// The description Orbit's bind carries, so it can tell its own bind from
/// conflicts.
pub const BIND_DESCRIPTION: &str = "Orbit overview";
/// The line to add to `hyprland.lua`.
pub const INCLUDE_LINE: &str = "require(\"hypr.orbit\")";

/// Another bind on the same keys: who it belongs to, for the dialog.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Conflict {
    pub description: String,
}

/// The Lua for one bind, from the snippet and the live `eval` alike.
pub fn bind_lua(shortcut: &Shortcut, exe: &Path) -> String {
    format!(
        "hl.bind({}, hl.dsp.exec_cmd({}), {{ description = {} }})",
        lua_string(&shortcut.lua_keys()),
        lua_string(&format!("{} toggle", exe.display())),
        lua_string(BIND_DESCRIPTION)
    )
}

pub fn unbind_lua(shortcut: &Shortcut) -> String {
    format!("hl.unbind({})", lua_string(&shortcut.lua_keys()))
}

/// A Lua double-quoted string.
pub fn lua_string(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 2);
    out.push('"');
    for c in text.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// The generated snippet's content.
pub fn snippet(shortcut: &Shortcut, exe: &Path) -> String {
    format!(
        "-- Generated by Orbit (the settings window or `orbit config`); rewritten\n\
         -- whenever the shortcut changes, so edit the setting, not this file.\n\
         -- Loaded by `{INCLUDE_LINE}` in ~/.config/hypr/hyprland.lua.\n\
         {}\n",
        bind_lua(shortcut, exe)
    )
}

/// `$XDG_CONFIG_HOME/hypr/orbit.lua`.
pub fn snippet_path() -> Option<PathBuf> {
    Some(hypr_dir()?.join("orbit.lua"))
}

/// `$XDG_CONFIG_HOME/hypr/hyprland.lua`, the person's own config.
pub fn hyprland_lua_path() -> Option<PathBuf> {
    Some(hypr_dir()?.join("hyprland.lua"))
}

fn hypr_dir() -> Option<PathBuf> {
    let config = std::env::var_os("XDG_CONFIG_HOME")
        .filter(|v| !v.is_empty())
        .map(PathBuf::from)
        .or_else(|| std::env::var_os("HOME").map(|h| PathBuf::from(h).join(".config")))?;
    Some(config.join("hypr"))
}

/// Writes the snippet atomically. Only Orbit's own file is touched.
pub fn write_snippet(path: &Path, shortcut: &Shortcut, exe: &Path) -> Result<(), String> {
    let dir = path.parent().ok_or("snippet path has no parent")?;
    fs::create_dir_all(dir).map_err(|e| format!("creating {}: {e}", dir.display()))?;
    let temp = dir.join(format!(".orbit.lua.{}.tmp", std::process::id()));
    let mut file =
        fs::File::create(&temp).map_err(|e| format!("writing {}: {e}", temp.display()))?;
    file.write_all(snippet(shortcut, exe).as_bytes())
        .and_then(|_| file.sync_all())
        .map_err(|e| format!("writing {}: {e}", temp.display()))?;
    drop(file);
    fs::rename(&temp, path).map_err(|e| {
        let _ = fs::remove_file(&temp);
        format!("replacing {}: {e}", path.display())
    })
}

/// Whether `hyprland.lua` already requires the snippet (ignoring comments).
pub fn include_present(hyprland_lua: &Path) -> bool {
    fs::read_to_string(hyprland_lua)
        .map(|text| {
            text.lines().any(|line| {
                let line = line.trim();
                !line.starts_with("--") && line.replace('\'', "\"").contains(INCLUDE_LINE)
            })
        })
        .unwrap_or(false)
}

/// Exactly what "Add it for me" appends to `hyprland.lua`.
pub fn include_block() -> String {
    format!("\n-- Orbit: the overview's shortcut (generated in hypr/orbit.lua).\n{INCLUDE_LINE}\n")
}

/// Appends [`include_block`] to `hyprland.lua`, once. Called only from the
/// settings window's confirmed button.
pub fn append_include(hyprland_lua: &Path) -> Result<(), String> {
    if include_present(hyprland_lua) {
        return Ok(());
    }
    let mut file = fs::OpenOptions::new()
        .append(true)
        .open(hyprland_lua)
        .map_err(|e| format!("opening {}: {e}", hyprland_lua.display()))?;
    file.write_all(include_block().as_bytes())
        .and_then(|_| file.sync_all())
        .map_err(|e| format!("writing {}: {e}", hyprland_lua.display()))
}

/// Binds that would fire on the same keys and are not Orbit's own.
pub fn conflicts(instance: &Instance, shortcut: &Shortcut) -> Vec<Conflict> {
    let Ok(binds) = instance.binds() else {
        return Vec::new();
    };
    conflicts_in(&binds, shortcut)
}

pub fn conflicts_in(binds: &serde_json::Value, shortcut: &Shortcut) -> Vec<Conflict> {
    let want_mask = u64::from(shortcut.modmask());
    binds
        .as_array()
        .into_iter()
        .flatten()
        .filter(|b| b["modmask"].as_u64() == Some(want_mask))
        .filter(|b| {
            b["key"]
                .as_str()
                .is_some_and(|k| k.eq_ignore_ascii_case(&shortcut.key))
        })
        .filter(|b| b["description"].as_str() != Some(BIND_DESCRIPTION))
        .map(|b| Conflict {
            description: b["description"]
                .as_str()
                .filter(|d| !d.is_empty())
                .map(str::to_owned)
                .unwrap_or_else(|| {
                    format!(
                        "{} {}",
                        b["dispatcher"].as_str().unwrap_or("bind"),
                        b["arg"].as_str().unwrap_or("")
                    )
                    .trim()
                    .to_owned()
                }),
        })
        .collect()
}

/// The shortcut to start with: Super+grave (the default), else the first
/// candidate nothing else uses. Super+Tab is not offered: Omarchy binds it.
pub fn pick_default(instance: Option<&Instance>) -> Shortcut {
    let candidates = [
        Shortcut::default(),
        Shortcut {
            mods: vec!["SUPER".into(), "SHIFT".into()],
            key: "grave".into(),
        },
        Shortcut {
            mods: vec!["SUPER".into(), "CTRL".into()],
            key: "Tab".into(),
        },
    ];
    let Some(instance) = instance else {
        return Shortcut::default();
    };
    let Ok(binds) = instance.binds() else {
        return Shortcut::default();
    };
    candidates
        .iter()
        .find(|c| conflicts_in(&binds, c).is_empty())
        .cloned()
        .unwrap_or_default()
}

/// The live bind Orbit holds in the running compositor.
#[derive(Default)]
pub struct LiveBind {
    bound: Option<Shortcut>,
}

impl LiveBind {
    /// Binds `shortcut` now (unbinding what this daemon bound before).
    pub fn apply(
        &mut self,
        instance: &Instance,
        shortcut: &Shortcut,
        exe: &Path,
    ) -> Result<(), String> {
        if self.bound.as_ref() == Some(shortcut) {
            return Ok(());
        }
        self.release(instance);
        match instance.eval(&bind_lua(shortcut, exe)) {
            Ok(Ok(())) => {
                self.bound = Some(shortcut.clone());
                Ok(())
            }
            Ok(Err(refused)) => Err(format!("Hyprland refused the bind: {refused}")),
            Err(error) => Err(format!("{error:#}")),
        }
    }

    /// Unbinds what this daemon bound, if anything.
    pub fn release(&mut self, instance: &Instance) {
        if let Some(previous) = self.bound.take()
            && let Err(error) = instance.eval(&unbind_lua(&previous))
        {
            log::warn!("unbinding {}: {error:#}", previous.label());
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lua_is_quoted_and_the_snippet_binds_toggle() {
        let s = Shortcut::default();
        let exe = Path::new("/opt/or\"bit/orbit");
        let lua = bind_lua(&s, exe);
        assert_eq!(
            lua,
            "hl.bind(\"SUPER+grave\", hl.dsp.exec_cmd(\"/opt/or\\\"bit/orbit toggle\"), { description = \"Orbit overview\" })"
        );
        assert_eq!(unbind_lua(&s), "hl.unbind(\"SUPER+grave\")");
        assert!(snippet(&s, exe).contains(INCLUDE_LINE));
        assert!(include_block().trim_end().ends_with(INCLUDE_LINE));
    }

    #[test]
    fn conflicts_match_mods_and_key_but_not_orbit_itself() {
        let binds = serde_json::json!([
            {"modmask": 64, "key": "TAB", "dispatcher": "__lua", "arg": "135", "description": "Cycle windows"},
            {"modmask": 64, "key": "Tab", "dispatcher": "exec", "arg": "orbit toggle", "description": "Orbit overview"},
            {"modmask": 65, "key": "TAB", "dispatcher": "__lua", "arg": "137", "description": ""},
            {"modmask": 64, "key": "grave", "dispatcher": "__lua", "arg": "1", "description": ""},
        ]);
        let tab = Shortcut {
            mods: vec!["SUPER".into()],
            key: "Tab".into(),
        };
        let found = conflicts_in(&binds, &tab);
        assert_eq!(found.len(), 1);
        assert_eq!(found[0].description, "Cycle windows");
        // The default, Super+grave, against an unlabelled Lua bind.
        let found = conflicts_in(&binds, &Shortcut::default());
        assert_eq!(found.len(), 1);
        assert_eq!(found[0].description, "__lua 1");
        let shifted = Shortcut {
            mods: vec!["SUPER".into(), "SHIFT".into()],
            key: "Tab".into(),
        };
        assert_eq!(conflicts_in(&binds, &shifted)[0].description, "__lua 137");
        let free = Shortcut {
            mods: vec!["SUPER".into()],
            key: "F12".into(),
        };
        assert!(conflicts_in(&binds, &free).is_empty());
    }

    #[test]
    fn include_detection_ignores_comments() {
        let dir = std::env::temp_dir().join(format!("orbit-engage-{}", std::process::id()));
        fs::create_dir_all(&dir).unwrap();
        let lua = dir.join("hyprland.lua");
        fs::write(
            &lua,
            "require(\"hypr.bindings\")\n-- require(\"hypr.orbit\")\n",
        )
        .unwrap();
        assert!(!include_present(&lua));
        append_include(&lua).unwrap();
        assert!(include_present(&lua));
        let once = fs::read_to_string(&lua).unwrap();
        append_include(&lua).unwrap();
        assert_eq!(fs::read_to_string(&lua).unwrap(), once);
        let _ = fs::remove_dir_all(dir);
    }
}
